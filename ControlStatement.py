# Control Statement : if, if-else, nested if, if-elif-else
# if statement
a = 10
if a > 5:
    print("a is greater than 5")

# if-else statement
b = 3
if b % 2 == 0:
    print("b is even")
else:
    print("b is odd")

# nested if statement
c = 15
if c > 10:
    if c % 2 == 0:
        print("c is greater than 10 and even")
    else:
        print("c is greater than 10 and odd")